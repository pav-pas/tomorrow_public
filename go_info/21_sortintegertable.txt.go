package piscine

func SortIntegerTable(table []int) { // []int — срез целых чисел
	n := len(table) // len() — длина среза

	for i := 0; i < n; i++ {
		for j := 0; j < n; j++ {
			if table[i] < table[j] {
				a := table[i]
				table[i] = table[j] // меняем элементы среза по индексу
				table[j] = a
			}
		}
	}
}

