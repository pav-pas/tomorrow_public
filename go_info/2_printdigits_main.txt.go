package main // main = запускаемая программа (не библиотека)

import "github.com/01-edu/z01"

func main() { // точка входа: go run начинает отсюда
	// for инициализация; условие; шаг
	// i типа rune: '0'..'9' идут подряд, поэтому i++ даёт следующую цифру
	for i := '0'; i <= '9'; i++ {
		z01.PrintRune(i)
	}
	z01.PrintRune('\n')
}

// Вывод: 0123456789
