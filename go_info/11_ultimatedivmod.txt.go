package piscine

func UltimateDivMod(a *int, b *int) {
	x := *a // ОБЯЗАТЕЛЬНО сохранить до перезаписи — иначе потеряем исходные значения
	y := *b
	*a = x / y
	*b = x % y
}

// x, y := 17, 5  →  UltimateDivMod(&x, &y)  →  x=3, y=2
