// В твоих решениях piscine:
//   import "github.com/01-edu/z01"
//   z01.PrintRune('A')   — печатает ОДИН символ на экран
//   z01.PrintRune('\n')  — перевод строки
//
// fmt.Println, fmt.Printf и подобное в задачах обычно ЗАПРЕЩЕНЫ.
//
// Ниже — исходник PrintRune «под капотом» + разбор синтаксиса Go,
// который встретится во всех следующих уроках.
//
// =============================================================================
// КАК ЧИТАТЬ ОБЪЯВЛЕНИЕ ФУНКЦИИ
// =============================================================================
//
//   func Имя(параметры) типВозврата { тело }
//
// Пример из этого файла:
//
//   func PrintRune(r rune) error {
//       ...
//   }
//
//   func       — ключевое слово «объявляем функцию»
//   PrintRune  — имя (с большой буквы = экспорт, видна снаружи пакета)
//   (r rune)   — один параметр: имя r, тип rune
//   error      — тип ВОЗВРАЩАЕМОГО значения (функция что-то отдаёт назад)
//   { ... }    — тело функции
//
// Может ли вместо error быть что-то другое? — ДА.
//
//   func Add(a int, b int) int { return a + b }     // возвращает int
//   func Hello() { fmt.Println("hi") }              // ничего не возвращает
//   func Div(a, b int) (int, int) { ... }           // два значения: частное и остаток
//
// Типы параметров:
//   (a int, b int)  — два int
//   (a, b int)      — сокращение: оба int
//   (s string)      — строка
//   (n *int)        — указатель (урок 10+)
//
// =============================================================================
// ЧТО ТАКОЕ error
// =============================================================================
//
// error — встроенный ТИП в Go для сообщения об ошибке.
// Это не исключение (как throw в других языках), а обычное возвращаемое значение.
//
//   return err        — вернуть ошибку вызывающему коду
//   return nil        — «ошибки нет, всё OK» (nil = пусто / ноль для указателей и error)
//
// Типичный вызов в «взрослом» Go:
//
//   err := z01.PrintRune('x')
//   if err != nil {
//       // что-то пошло не так
//   }
//
// В piscine чаще пишут просто:
//
//   z01.PrintRune('x')   // ошибку игнорируют — для учебных задач это нормально
//
// errors.New("текст") — создаёт значение типа error с сообщением.
//
// =============================================================================
// package и import
// =============================================================================
//
//   package z01  — этот файл принадлежит пакету z01 (имя папки/модуля)
//
//   import ( ... ) — подключение чужого кода; в скобках — список пакетов:
//     "errors"      — стандартная библиотека: создание error
//     "os"          — операционная система: файлы, stdout
//     "unicode/utf8" — кодирование символов в UTF-8
//
// В твоих файлах piscine обычно:
//   package piscine
//   import "github.com/01-edu/z01"
//
// =============================================================================

package z01

import (
	"errors"
	"os"
	"unicode/utf8"
)

func PrintRune(r rune) error {
	// --- utf8.RuneLen(r) ---
	// Встроенная функция: сколько БАЙТ нужно для символа r в кодировке UTF-8.
	// Возвращает int: 1..4 или -1 если символ невалидный.
	//
	// Параметр: r rune — один символ.
	// Возврат:  int
	l := utf8.RuneLen(r)

	if l == -1 {
		// return — выход из функции И передача значения тому, кто вызвал PrintRune
		return errors.New("The rune is not a valid value to encode in UTF-8")
	}

	// --- make([]byte, l) ---
	// make — встроенная функция: СОЗДАЬ срез/карту/канал с заданной длиной.
	//
	//   make([]byte, l)
	//        ^^^^^^  ^ тип: срез байт (массив байт переменной длины)
	//               ^ l — длина среза (сколько элементов)
	//
	// Альтернатива make для срезов с данными:
	//   p := []byte{72, 105}   — литерал среза с начальными значениями
	//
	// make vs new:
	//   make — создаёт срез/мап/канал, готовый к использованию
	//   new  — выделяет память под один объект, возвращает указатель (в piscine редко)
	//
	// Здесь p — буфер из l байт, куда положим UTF-8 представление символа.
	p := make([]byte, l)

	// --- utf8.EncodeRune(p, r) ---
	// Записывает символ r в срез p в формате UTF-8.
	// Параметры: (куда писать []byte, что кодировать rune)
	// Возвращает: int — сколько байт записано (здесь не используем)
	utf8.EncodeRune(p, r)

	// --- os.Stdout.Write(p) ---
	// Stdout — стандартный поток вывода (терминал / экран).
	// Write(p) — записать байты из среза p в stdout.
	//
	// Возвращает ДВА значения (в Go так можно):
	//   (количество записанных байт, error)
	//
	//   _, err := os.Stdout.Write(p)
	//   ^       ^_____________________
	//   |       присваивание двух значений сразу
	//   _ — «пустой идентификатор»: первое значение выбрасываем, не нужно
	//
	// Можно ли вместо _ написать имя? Да:
	//   n, err := os.Stdout.Write(p)   // n — сколько байт записали
	_, err := os.Stdout.Write(p)

	// Вернуть err вызывающему: nil если запись OK, иначе описание ошибки
	return err
}

// =============================================================================
// ТИПЫ, КОТОРЫЕ ВСТРЕТИШЬ В УРОКАХ
// =============================================================================
//
//   int    — целое число: -5, 0, 42
//   rune   — один символ Unicode (по сути int32): 'A', '0', '\n'
//   string — строка: "hello"
//   bool   — true / false
//   byte   — байт 0..255 (alias uint8); символ в ASCII — один байт
//   []int  — срез int (урок 21)
//   []rune — срез символов (урок 16+)
//   *int   — указатель на int (урок 10+)
//   error  — ошибка (этот файл)
//
// =============================================================================
// ОБЪЯВЛЕНИЕ ПЕРЕМЕННЫХ (кратко)
// =============================================================================
//
//   l := utf8.RuneLen(r)   // := создаёт переменную и присваивает (тип выводится сам)
//   var n int = 10         // явный тип
//   var s string             // нулевое значение: 0, "", false, nil
//
// Имя с _ в начале не экспортируется; одиночный _ — «выбросить значение».
//
// =============================================================================
// rune И СПЕЦСИМВОЛЫ
// =============================================================================
//
//   '0' 'A' 'Ж'     — литерал rune (одинарные кавычки)
//   '\n'            — новая строка
//   '\t'            — табуляция
//   '\\' '\''       — экранирование
//
// Символы '0'..'9' в Unicode идут подряд — в циклах можно делать i++ (урок 2).
//
// =============================================================================
// ASCII-СПРАВКА (уроки 4+)
// =============================================================================
//
//   10 → '\n'     32 → ' '     44 → ','
//   48 → '0'  …   57 → '9'
//
//   z01.PrintRune(44)  — то же, что  z01.PrintRune(',')
//
// =============================================================================
// СВЯЗЬ С ТВОИМИ ЗАДАЧАМИ
// =============================================================================
//
// Тебе НЕ нужно писать PrintRune — только вызывать:
//
//   package piscine
//   import "github.com/01-edu/z01"
//
//   func IsNegative(nb int) {          // без error в возврате — просто печатаем
//       z01.PrintRune('T')
//   }
//
// Когда в задаче разрешено только z01.PrintRune и --allow-builtin —
// имеются в виду встроенные функции Go (len, make, append…) и твой код,
// но НЕ fmt, strconv и т.д. (смотри условие каждой задачи).
