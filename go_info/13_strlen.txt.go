// НОВОЕ: срез []rune, преобразование string → []rune, range только по индексу
// =============================================================================

package piscine

func StrLen(str string) int {
	astr := []rune(str) // СРЕЗ рун — строка как изменяемый массив символов
	a := 1
	for index := range astr { // range без значения — только индексы 0, 1, 2...
		a = index
	}
	return a + 1 // длина = последний индекс + 1
}
