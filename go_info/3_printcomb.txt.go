// НОВОЕ: вложенные циклы, оператор ||, формат вывода «запятая кроме последней»
// =============================================================================
//
// Задача: все тройки разных цифр по возрастанию → 012, 013, ... 789
//
// =============================================================================

package piscine

import "github.com/01-edu/z01"

func PrintComb() {
	// ВЛОЖЕННЫЕ циклы: внешний i, внутри j, внутри k
	// Границы циклов сразу дают i < j < k (j от i+1, k от j+1)
	for i := '0'; i <= '7'; i++ {
		for j := i + 1; j <= '8'; j++ {
			for k := j + 1; k <= '9'; k++ {
				z01.PrintRune(i)
				z01.PrintRune(j)
				z01.PrintRune(k)

				// || — ИЛИ: условие true, если хотя бы одна часть true
				// Запятая везде, кроме последней комбинации 789
				if i != '7' || j != '8' || k != '9' {
					z01.PrintRune(',')
					z01.PrintRune(' ')
				}
			}
		}
	}
	z01.PrintRune('\n')
}
