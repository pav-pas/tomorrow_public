// package piscine — все наши учебные функции лежат в одном пакете.
// Имя пакета должно совпадать во всех .go файлах этой папки.
package piscine

// import подключает чужой код. Здесь — библиотеку школы 01-edu.
// z01.PrintRune печатает ОДИН символ (rune) в терминал.
// Rune в Go — это символ Unicode (по сути "буква/знак").
import (
	"github.com/01-edu/z01"
)

// quadconditionA решает: КАКОЙ символ поставить в клетке (i, j).
//
// Параметры:
//   x — ширина прямоугольника (сколько символов в одной строке)
//   y — высота прямоугольника (сколько строк)
//   i — номер столбца текущей клетки (слева направо: 0, 1, 2, ...)
//   j — номер строки текущей клетки (сверху вниз: 0, 1, 2, ...)
//
// Картинка координат (пример x=5, y=3):
//
//   i→  0 1 2 3 4
// j 0   o - - - o
// ↓ 1   |       |
//   2   o - - - o
//
// Углы = 'o', боковые стороны = '|', верх/низ = '-', внутри = пробел.
func quadconditionA(x int, y int, i int, j int) {
	// УГОЛ: клетка и на краю по горизонтали, и на краю по вертикали.
	// i == 0        → левый край
	// i == x-1      → правый край (последний столбец)
	// j == 0        → верхний край
	// j == y-1      → нижний край (последняя строка)
	if (i == 0 || i == x-1) && (j == 0 || j == y-1) {
		z01.PrintRune('o')

		// БОКОВАЯ СТОРОНА (слева или справа), но НЕ угол.
		// (j != 0 || j != y-1) здесь всегда true для не-углов по смыслу условия выше:
		// мы уже в ветке "не угол", потому что if выше не сработал.
	} else if (i == 0 || i == x-1) && (j != 0 || j != y-1) {
		z01.PrintRune('|')

		// ВЕРХ или НИЗ (горизонтальная рамка), но НЕ угол.
	} else if (j == 0 || j == y-1) && (i != 0 || i != x-1) {
		z01.PrintRune('-')

		// Всё остальное — внутри прямоугольника → пустое место.
	} else {
		z01.PrintRune(' ')
	}
}

// QuadA — ГЛАВНАЯ функция. Её вызывают снаружи: QuadA(ширина, высота).
// Она рисует весь прямоугольник посимвольно.
//
// Пример: QuadA(5, 3) напечатает:
// o---o
// |   |
// o---o
func QuadA(x, y int) {
	// Защита: если ширина или высота <= 0 — ничего не рисуем.
	// (отрицательный или нулевой прямоугольник не имеет смысла)
	if x > 0 && y > 0 {

		// Внешний цикл: идём ПО СТРОКАМ сверху вниз.
		// j = 0 — первая (верхняя) строка
		// j = y-1 — последняя (нижняя) строка
		for j := 0; j < y; j++ {

			// Внутренний цикл: внутри одной строки идём ПО СТОЛБЦАМ слева направо.
			// i = 0 — первый (левый) символ
			// i = x-1 — последний (правый) символ
			for i := 0; i < x; i++ {
				// Для каждой клетки спрашиваем: какой символ сюда?
				quadconditionA(x, y, i, j)
			}

			// После всей строки обязательно перевод строки '\n',
			// иначе следующий ряд прилипнет к текущему в одну линию.
			z01.PrintRune('\n')
		}
	}
}
