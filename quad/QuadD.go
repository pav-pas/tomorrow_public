package piscine

// z01.PrintRune печатает один символ в stdout (терминал).
import (
	"github.com/01-edu/z01"
)

// quadconditionD выбирает символ для клетки (i, j) в стиле QuadD.
//
// Параметры:
//   x — ширина, y — высота
//   i — столбец (0 … x-1), j — строка (0 … y-1)
//
// Картинка (пример x=5, y=3):
//
//   ABBBC
//   B   B
//   ABBBC
//
// Отличие от QuadC: здесь 'A' и 'C' стоят СЛЕВА и СПРАВА,
// а не сверху и снизу.
//   левые углы  = 'A'
//   правые углы = 'C'
//   остальные края = 'B'
//   внутри = пробел
func quadconditionD(x int, y int, i int, j int) {
	// ЛЕВЫЙ край (i == 0) И это верх или низ → угол 'A'
	if (i == 0) && (j == 0 || j == y-1) {
		z01.PrintRune('A')

		// ПРАВЫЙ край (i == x-1) И это верх или низ → угол 'C'
	} else if (i == x-1) && (j == 0 || j == y-1) {
		z01.PrintRune('C')

		// Левая или правая сторона, но НЕ угол → 'B'
		// Здесь уже && в проверке j: j не 0 И не y-1 (строго середина по вертикали).
	} else if (i == 0 || i == x-1) && (j != 0 && j != y-1) {
		z01.PrintRune('B')

		// Верхняя или нижняя сторона, но НЕ угол → 'B'
		// i не 0 И не x-1 (строго середина по горизонтали).
	} else if (j == 0 || j == y-1) && (i != 0 && i != x-1) {
		z01.PrintRune('B')

		// Внутри прямоугольника — пробел.
	} else {
		z01.PrintRune(' ')
	}
}

// QuadD — главная функция: печатает весь прямоугольник.
//
// Пример: QuadD(5, 3) →
// ABBBC
// B   B
// ABBBC
func QuadD(x, y int) {
	// Рисуем только при положительных размерах.
	if x > 0 && y > 0 {

		// Двойной цикл: строка → символы в строке.
		for j := 0; j < y; j++ {
			for i := 0; i < x; i++ {
				quadconditionD(x, y, i, j)
			}
			// Enter после каждой строки.
			z01.PrintRune('\n')
		}
	}
}
