// package piscine — все учебные функции лежат в одном пакете.
package piscine

// z01.PrintRune печатает один символ в терминал.
import (
	"github.com/01-edu/z01"
)

// quadconditionB выбирает символ для клетки (i, j) в стиле QuadB.
//
// Параметры:
//   x — ширина, y — высота
//   i — столбец (0 … x-1), j — строка (0 … y-1)
//
// Картинка (пример x=5, y=3):
//
//   /****\
//   *    *
//   \****/
//
// Углы: '/' и '\', рамка: '*', внутри: пробел.
func quadconditionB(x int, y int, i int, j int) {
	// ВЕРХНИЙ-ЛЕВЫЙ угол → '/'
	// или НИЖНИЙ-ПРАВЫЙ угол → '/'
	//
	// Важно про && и || в Go:
	//   A || B && C  читается как  A || (B && C)
	// (сначала &&, потом || — как умножение раньше сложения).
	// Доп. проверка (y != 1 && x != 1) нужна для особых случаев
	// толщины 1×1 / одной строки / одного столбца.
	if (i == 0 && j == 0) || (i == x-1 && j == y-1) && (y != 1 && x != 1) {
		z01.PrintRune('/')

		// НИЖНИЙ-ЛЕВЫЙ угол → '\'
		// или ВЕРХНИЙ-ПРАВЫЙ угол → '\'
		// В Go '\\' — это один символ обратного слэша
		// (первый \ экранирует второй, как в строках).
	} else if (j == y-1 && i == 0) || (j == 0 && i == x-1) {
		z01.PrintRune('\\')

		// Левая или правая СТОРОНА (вертикальная рамка) → '*'
	} else if (i == 0 || i == x-1) && (j != 0 || j != y-1) {
		z01.PrintRune('*')

		// Верхняя или нижняя СТОРОНА (горизонтальная рамка) → '*'
	} else if (j == 0 || j == y-1) && (i != 0 || i != x-1) {
		z01.PrintRune('*')

		// Внутри прямоугольника — пусто.
	} else {
		z01.PrintRune(' ')
	}
}

// QuadB рисует весь прямоугольник: строки сверху вниз, в строке — слева направо.
//
// Пример: QuadB(5, 3) →
// /****\
// *    *
// \****/
func QuadB(x, y int) {
	// Не рисуем, если размеры неположительные.
	if x > 0 && y > 0 {

		// j — номер строки (сверху вниз).
		for j := 0; j < y; j++ {

			// i — номер столбца (слева направо).
			for i := 0; i < x; i++ {
				quadconditionB(x, y, i, j)
			}

			// Конец строки → Enter.
			z01.PrintRune('\n')
		}
	}
}
