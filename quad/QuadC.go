package piscine

// z01.PrintRune — печать одного символа (как putchar в C).
import (
	"github.com/01-edu/z01"
)

// quadconditionC выбирает символ для клетки (i, j) в стиле QuadC.
//
// Параметры:
//   x — ширина, y — высота
//   i — столбец (0 … x-1), j — строка (0 … y-1)
//
// Картинка (пример x=5, y=3):
//
//   ABBBA
//   B   B
//   CBBBC
//
// Верхние углы = 'A', нижние углы = 'C', остальные края = 'B', внутри = пробел.
func quadconditionC(x int, y int, i int, j int) {
	// ВЕРХНЯЯ строка (j == 0) И клетка — левый или правый угол → 'A'
	if j == 0 && (i == 0 || i == x-1) {
		z01.PrintRune('A')

		// НИЖНЯЯ строка (j == y-1) И клетка — левый или правый угол → 'C'
	} else if j == y-1 && (i == 0 || i == x-1) {
		z01.PrintRune('C')

		// Верх или низ, но НЕ угол → 'B' (горизонтальная рамка)
	} else if (j == 0 || j == y-1) && (i != 0 || i != x-1) {
		z01.PrintRune('B')

		// Лево или право, но НЕ угол → 'B' (вертикальная рамка)
	} else if (i == 0 || i == x-1) && (j != 0 || j != y-1) {
		z01.PrintRune('B')

		// Внутри — пробел.
	} else {
		z01.PrintRune(' ')
	}
}

// QuadC — главная функция: печатает весь прямоугольник.
//
// Пример: QuadC(5, 3) →
// ABBBA
// B   B
// CBBBC
func QuadC(x, y int) {
	// Если x или y <= 0 — выходим без печати.
	if x > 0 && y > 0 {

		// Сначала строки (j), потом столбцы (i).
		for j := 0; j < y; j++ {
			for i := 0; i < x; i++ {
				// На каждую клетку — свой символ через условия выше.
				quadconditionC(x, y, i, j)
			}
			// После строки — перевод строки.
			z01.PrintRune('\n')
		}
	}
}
