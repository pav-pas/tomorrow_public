package piscine

// z01.PrintRune — печать одного символа (библиотека школы 01).
import (
	"github.com/01-edu/z01"
)

// quadconditionE выбирает символ для клетки (i, j) в стиле QuadE.
//
// Параметры:
//   x — ширина, y — высота
//   i — столбец (0 … x-1), j — строка (0 … y-1)
//
// Картинка (пример x=5, y=3):
//
//   ABBBC
//   B   B
//   CBBBA
//
// Углы по диагонали:
//   верх-лево и низ-право → 'A'
//   низ-лево и верх-право → 'C'
// Остальные края → 'B', внутри → пробел.
//
// Похоже на QuadB, только вместо '/' и '\' — буквы 'A' и 'C'.
func quadconditionE(x int, y int, i int, j int) {
	// ВЕРХНИЙ-ЛЕВЫЙ угол → 'A'
	// или НИЖНИЙ-ПРАВЫЙ угол → 'A'
	//
	// Приоритет операторов: && сильнее ||,
	// поэтому выражение читается как:
	//   (i==0 && j==0)  ||  ((i==x-1 && j==y-1) && (y!=1 && x!=1))
	// Проверка x!=1 && y!=1 — на крайние случаи 1×N / N×1 / 1×1.
	if (i == 0 && j == 0) || (i == x-1 && j == y-1) && (y != 1 && x != 1) {
		z01.PrintRune('A')

		// НИЖНИЙ-ЛЕВЫЙ угол → 'C'
		// или ВЕРХНИЙ-ПРАВЫЙ угол → 'C'
	} else if (i == 0 && j == y-1) || (i == x-1 && j == 0) {
		z01.PrintRune('C')

		// Левая/правая сторона (не угол) → 'B'
	} else if (i == 0 || i == x-1) && (j != 0 && j != y-1) {
		z01.PrintRune('B')

		// Верх/низ (не угол) → 'B'
	} else if (j == 0 || j == y-1) && (i != 0 && i != x-1) {
		z01.PrintRune('B')

		// Внутри — пробел.
	} else {
		z01.PrintRune(' ')
	}
}

// QuadE — главная функция: печатает весь прямоугольник.
//
// Пример: QuadE(5, 3) →
// ABBBC
// B   B
// CBBBA
func QuadE(x, y int) {
	// Без положительных размеров — ничего не печатаем.
	if x > 0 && y > 0 {

		// j — строка сверху вниз, i — столбец слева направо.
		for j := 0; j < y; j++ {
			for i := 0; i < x; i++ {
				quadconditionE(x, y, i, j)
			}
			// Перевод строки после полного ряда.
			z01.PrintRune('\n')
		}
	}
}
